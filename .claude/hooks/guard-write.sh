#!/usr/bin/env bash
# PreToolUse Write|Edit|MultiEdit|NotebookEdit: deny secrets, generated trees, and any .superpowers/ path outside specs/, plans/, and sdd/.
set -euo pipefail

path=$(jq -r '.tool_input.file_path // .tool_input.notebook_path // empty')
[ -n "$path" ] || exit 0

root="${CLAUDE_PROJECT_DIR:-$(git rev-parse --show-toplevel 2>/dev/null || pwd)}"
rel="${path#"$root"/}"

deny() {
    jq -cn --arg reason "$1" \
        '{hookSpecificOutput:{hookEventName:"PreToolUse",permissionDecision:"deny",permissionDecisionReason:$reason}}'
    exit 0
}

skill_output="Under .superpowers/, a plan goes to plans/YYYY-MM-DD-<slug>.md, a design to specs/YYYY-MM-DD-<topic>-design.md, and the subagent-driven-development workspace to sdd/<plan-basename>/; nothing else goes under .superpowers/. generated/docs/ holds agent reports, the sweep log, and PR, comment, and version text."

case "$rel" in
    .env.example|*/.env.example) ;;
    .env|.env.*|*/.env|*/.env.*)
        deny "$rel is the owner's environment file. Change .env.example and hand the variable back."
        ;;
esac

case "$rel" in
    keys/*|*/keys/*)
        deny "keys/ is generated by pnpm generate:secret and gitignored. Do not write it."
        ;;
    generated/docs/pr-*|generated/docs/version-*) ;;
    generated/docs/*-spec.md|generated/docs/*-plan.md|generated/docs/*-design.md)
        deny "$rel is not a report. $skill_output"
        ;;
    generated/docs/*) ;;
    generated/*|*/generated/*)
        deny "src/generated/ is produced by pnpm generate; generated/swagger.json by src/swagger.ts and generated/vault/ by the Vault containers. Reports go to generated/docs/."
        ;;
    docs/superpowers/*|*/docs/superpowers/*)
        deny "docs/ is tracked project documentation. $skill_output"
        ;;
    .superpowers/specs/*|*/.superpowers/specs/*) ;;
    .superpowers/plans/*|*/.superpowers/plans/*) ;;
    .superpowers/sdd/*|*/.superpowers/sdd/*) ;;
    .superpowers/*|*/.superpowers/*)
        deny "$rel is outside .superpowers/specs/, plans/, and sdd/. $skill_output"
        ;;
esac

exit 0
