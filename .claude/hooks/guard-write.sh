#!/usr/bin/env bash
# PreToolUse Write|Edit|MultiEdit|NotebookEdit: deny secrets, generated trees, a copied skill by either path, and a lint
# suppression or a focused or skipped spec.
set -euo pipefail

payload=$(cat)
path=$(printf '%s' "$payload" | jq -r '.tool_input.file_path // .tool_input.notebook_path // empty')
[ -n "$path" ] || exit 0

root="${CLAUDE_PROJECT_DIR:-$(git rev-parse --show-toplevel 2>/dev/null || pwd)}"
rel="${path#"$root"/}"

deny() {
    jq -cn --arg reason "$1" \
        '{hookSpecificOutput:{hookEventName:"PreToolUse",permissionDecision:"deny",permissionDecisionReason:$reason}}'
    exit 0
}

case "$rel" in
    .env.example|*/.env.example) ;;
    .env|.env.*|*/.env|*/.env.*)
        deny "$rel is the owner's environment file. Change .env.example and hand the variable back; a DOCKER_ key is the owner's to add."
        ;;
esac

case "$rel" in
    keys/*|*/keys/*)
        deny "keys/ is generated by pnpm generate:secret and gitignored. Do not write it."
        ;;
    generated/report-src-sweep.md) ;;
    generated/*|*/generated/*)
        deny "src/generated/ is produced by pnpm generate; generated/swagger.json by src/swagger.ts, generated/vault/ by the Vault containers, and generated/raw-plan.md is the owner's. The sweep log is generated/report-src-sweep.md; a feature's spec, tickets, plan, and review go to .scratch/<feature>/, a requirement to .scratch/requirements/, PR text to .scratch/pr/."
        ;;
    .claude/skills/ack-*) ;;
    .claude/skills/*/*|.agents/*)
        deny "$rel belongs to a copied skill (skills-lock.json) or reaches .claude/skills/ through the .agents/skills symlink. A copied skill is never edited: adapt it in the ack-* skill or the agent that follows it, and update it with pnpm skills:update. An ack-* skill is edited under .claude/skills/."
        ;;
esac

written=$(printf '%s' "$payload" | jq -r '[.tool_input.content, .tool_input.new_string, (.tool_input.edits[]?.new_string)] | map(select(. != null)) | join("\n")')

case "$rel" in
    src/*|test/*)
        if printf '%s' "$written" | grep -q 'eslint-disable'; then
            deny "$rel: no eslint-disable comment. Fix the code, or hand the rule back as a question."
        fi
        ;;
esac

case "$rel" in
    test/*)
        if printf '%s' "$written" | grep -qE '(describe|it|test)(\.[a-zA-Z]+)*\.(only|skip)[[:space:]]*[(.]'; then
            deny "$rel: no .only or .skip. A spec that cannot pass is a hand-back, not a skipped spec."
        fi
        ;;
esac

exit 0
